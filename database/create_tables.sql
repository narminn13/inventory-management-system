
-- ============================================
-- INVENTORY & WAREHOUSE MANAGEMENT SYSTEM
-- STAGE 2: DATABASE TABLE CREATION
-- ============================================

-- 1. CATEGORIES

CREATE TABLE categories (
    category_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    category_name VARCHAR2(100) NOT NULL,
    description VARCHAR2(500),
    created_at DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT pk_categories PRIMARY KEY (category_id),
    CONSTRAINT uq_category_name UNIQUE (category_name)
);

-- 2. PRODUCTS

CREATE TABLE products (
    product_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    category_id NUMBER NOT NULL,
    sku VARCHAR2(50) NOT NULL,
    product_name VARCHAR2(150) NOT NULL,
    description VARCHAR2(500),
    unit_of_measure VARCHAR2(20) DEFAULT 'UNIT' NOT NULL,
    selling_price NUMBER(12,2) DEFAULT 0 NOT NULL,
    reorder_level NUMBER(12,2) DEFAULT 0 NOT NULL,
    is_active CHAR(1) DEFAULT 'Y' NOT NULL,
    created_at DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT pk_products PRIMARY KEY (product_id),
    CONSTRAINT uq_products_sku UNIQUE (sku),
    CONSTRAINT fk_products_category
        FOREIGN KEY (category_id)
        REFERENCES categories(category_id),
    CONSTRAINT chk_product_price CHECK (selling_price >= 0),
    CONSTRAINT chk_reorder_level CHECK (reorder_level >= 0),
    CONSTRAINT chk_product_active CHECK (is_active IN ('Y','N'))
);

-- 3. SUPPLIERS

CREATE TABLE suppliers (
    supplier_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    supplier_name VARCHAR2(150) NOT NULL,
    contact_person VARCHAR2(100),
    email VARCHAR2(150),
    phone VARCHAR2(30),
    address VARCHAR2(300),
    is_active CHAR(1) DEFAULT 'Y' NOT NULL,
    created_at DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT pk_suppliers PRIMARY KEY (supplier_id),
    CONSTRAINT chk_supplier_active CHECK (is_active IN ('Y','N'))
);

-- 4. WAREHOUSES

CREATE TABLE warehouses (
    warehouse_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    warehouse_name VARCHAR2(150) NOT NULL,
    location VARCHAR2(250) NOT NULL,
    capacity NUMBER(14,2),
    is_active CHAR(1) DEFAULT 'Y' NOT NULL,
    created_at DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT pk_warehouses PRIMARY KEY (warehouse_id),
    CONSTRAINT uq_warehouse_name UNIQUE (warehouse_name),
    CONSTRAINT chk_warehouse_capacity CHECK (capacity IS NULL OR capacity >= 0),
    CONSTRAINT chk_warehouse_active CHECK (is_active IN ('Y','N'))
);

-- 5. INVENTORY

CREATE TABLE inventory (
    inventory_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    warehouse_id NUMBER NOT NULL,
    product_id NUMBER NOT NULL,
    quantity_on_hand NUMBER(14,2) DEFAULT 0 NOT NULL,
    quantity_reserved NUMBER(14,2) DEFAULT 0 NOT NULL,
    average_unit_cost NUMBER(14,4) DEFAULT 0 NOT NULL,
    last_updated DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT pk_inventory PRIMARY KEY (inventory_id),
    CONSTRAINT fk_inventory_warehouse
        FOREIGN KEY (warehouse_id)
        REFERENCES warehouses(warehouse_id),
    CONSTRAINT fk_inventory_product
        FOREIGN KEY (product_id)
        REFERENCES products(product_id),
    CONSTRAINT uq_inventory_product_warehouse
        UNIQUE (warehouse_id, product_id),
    CONSTRAINT chk_inventory_quantity
        CHECK (quantity_on_hand >= 0 AND quantity_reserved >= 0),
    CONSTRAINT chk_inventory_reserved
        CHECK (quantity_reserved <= quantity_on_hand),
    CONSTRAINT chk_inventory_cost
        CHECK (average_unit_cost >= 0)
);

-- 6. PURCHASE ORDERS

CREATE TABLE purchase_orders (
    purchase_order_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    supplier_id NUMBER NOT NULL,
    warehouse_id NUMBER NOT NULL,
    order_date DATE DEFAULT SYSDATE NOT NULL,
    expected_date DATE,
    status VARCHAR2(30) DEFAULT 'DRAFT' NOT NULL,
    created_at DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT pk_purchase_orders PRIMARY KEY (purchase_order_id),
    CONSTRAINT fk_po_supplier
        FOREIGN KEY (supplier_id) REFERENCES suppliers(supplier_id),
    CONSTRAINT fk_po_warehouse
        FOREIGN KEY (warehouse_id) REFERENCES warehouses(warehouse_id),
    CONSTRAINT chk_po_status
        CHECK (status IN ('DRAFT','APPROVED','PARTIALLY_RECEIVED',
                          'RECEIVED','CANCELLED')),
    CONSTRAINT chk_po_dates
        CHECK (expected_date IS NULL OR expected_date >= order_date)
);

-- 7. PURCHASE ORDER ITEMS

CREATE TABLE purchase_order_items (
    purchase_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    purchase_order_id NUMBER NOT NULL,
    product_id NUMBER NOT NULL,
    quantity_ordered NUMBER(14,2) NOT NULL,
    quantity_received NUMBER(14,2) DEFAULT 0 NOT NULL,
    unit_cost NUMBER(14,4) NOT NULL,

    CONSTRAINT pk_purchase_items PRIMARY KEY (purchase_item_id),
    CONSTRAINT fk_poi_order
        FOREIGN KEY (purchase_order_id)
        REFERENCES purchase_orders(purchase_order_id),
    CONSTRAINT fk_poi_product
        FOREIGN KEY (product_id) REFERENCES products(product_id),
    CONSTRAINT uq_purchase_order_product
        UNIQUE (purchase_order_id, product_id),
    CONSTRAINT chk_poi_quantity
        CHECK (quantity_ordered > 0 AND
               quantity_received >= 0 AND
               quantity_received <= quantity_ordered),
    CONSTRAINT chk_poi_cost CHECK (unit_cost >= 0)
);

-- 8. SALES ORDERS

CREATE TABLE sales_orders (
    sales_order_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    customer_name VARCHAR2(150) NOT NULL,
    customer_email VARCHAR2(150),
    warehouse_id NUMBER NOT NULL,
    order_date DATE DEFAULT SYSDATE NOT NULL,
    status VARCHAR2(30) DEFAULT 'DRAFT' NOT NULL,
    created_at DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT pk_sales_orders PRIMARY KEY (sales_order_id),
    CONSTRAINT fk_so_warehouse
        FOREIGN KEY (warehouse_id)
        REFERENCES warehouses(warehouse_id),
    CONSTRAINT chk_so_status
        CHECK (status IN ('DRAFT','CONFIRMED','FULFILLED','CANCELLED'))
);

-- 9. SALES ORDER ITEMS

CREATE TABLE sales_order_items (
    sales_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    sales_order_id NUMBER NOT NULL,
    product_id NUMBER NOT NULL,
    quantity NUMBER(14,2) NOT NULL,
    unit_price NUMBER(14,2) NOT NULL,

    CONSTRAINT pk_sales_items PRIMARY KEY (sales_item_id),
    CONSTRAINT fk_soi_order
        FOREIGN KEY (sales_order_id)
        REFERENCES sales_orders(sales_order_id),
    CONSTRAINT fk_soi_product
        FOREIGN KEY (product_id) REFERENCES products(product_id),
    CONSTRAINT uq_sales_order_product
        UNIQUE (sales_order_id, product_id),
    CONSTRAINT chk_soi_quantity CHECK (quantity > 0),
    CONSTRAINT chk_soi_price CHECK (unit_price >= 0)
);

-- 10. STOCK MOVEMENTS

CREATE TABLE stock_movements (
    movement_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    inventory_id NUMBER NOT NULL,
    movement_type VARCHAR2(30) NOT NULL,
    quantity NUMBER(14,2) NOT NULL,
    reference_type VARCHAR2(30),
    reference_id NUMBER,
    movement_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    notes VARCHAR2(500),

    CONSTRAINT pk_stock_movements PRIMARY KEY (movement_id),
    CONSTRAINT fk_sm_inventory
        FOREIGN KEY (inventory_id) REFERENCES inventory(inventory_id),
    CONSTRAINT chk_movement_type
        CHECK (movement_type IN (
            'PURCHASE_RECEIPT',
            'SALES_FULFILLMENT',
            'TRANSFER_OUT',
            'TRANSFER_IN',
            'SALES_RETURN',
            'PURCHASE_RETURN',
            'STOCK_ADJUSTMENT'
        )),
    CONSTRAINT chk_movement_quantity CHECK (quantity > 0)
);

-- 11. STOCK TRANSFERS

CREATE TABLE stock_transfers (
    transfer_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    source_warehouse_id NUMBER NOT NULL,
    destination_warehouse_id NUMBER NOT NULL,
    transfer_date DATE DEFAULT SYSDATE NOT NULL,
    status VARCHAR2(30) DEFAULT 'DRAFT' NOT NULL,
    notes VARCHAR2(500),

    CONSTRAINT pk_stock_transfers PRIMARY KEY (transfer_id),
    CONSTRAINT fk_transfer_source
        FOREIGN KEY (source_warehouse_id)
        REFERENCES warehouses(warehouse_id),
    CONSTRAINT fk_transfer_destination
        FOREIGN KEY (destination_warehouse_id)
        REFERENCES warehouses(warehouse_id),
    CONSTRAINT chk_transfer_warehouses
        CHECK (source_warehouse_id <> destination_warehouse_id),
    CONSTRAINT chk_transfer_status
        CHECK (status IN ('DRAFT','APPROVED','IN_TRANSIT',
                          'RECEIVED','CANCELLED'))
);

-- 12. STOCK TRANSFER ITEMS

CREATE TABLE stock_transfer_items (
    transfer_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    transfer_id NUMBER NOT NULL,
    product_id NUMBER NOT NULL,
    quantity NUMBER(14,2) NOT NULL,
    quantity_received NUMBER(14,2) DEFAULT 0 NOT NULL,

    CONSTRAINT pk_transfer_items PRIMARY KEY (transfer_item_id),
    CONSTRAINT fk_sti_transfer
        FOREIGN KEY (transfer_id) REFERENCES stock_transfers(transfer_id),
    CONSTRAINT fk_sti_product
        FOREIGN KEY (product_id) REFERENCES products(product_id),
    CONSTRAINT uq_transfer_product
        UNIQUE (transfer_id, product_id),
    CONSTRAINT chk_transfer_item_quantity
        CHECK (quantity > 0 AND
               quantity_received >= 0 AND
               quantity_received <= quantity)
);
